"""Practice-system port: the read-only clinic records the app depends on.

The app only talks to this interface. `EzyVetPracticeSystem` (integrations/ezyvet.py)
implements it; other practice systems can implement it without touching the domain, agent or
API code.
"""

from typing import Protocol

from vetagent.domain.estimates import Estimate
from vetagent.domain.models import (
    BenefitUse,
    CareEvent,
    ClinicContact,
    Membership,
    Owner,
    Pet,
    Plan,
)


class PracticeSystem(Protocol):
    def clinic_name(self) -> str: ...
    def lead_vet(self) -> str: ...
    def price_list(self) -> dict[str, int]: ...
    def pets(self) -> list[Pet]: ...
    def pet(self, pet_id: str) -> Pet: ...
    def owner(self, owner_id: str) -> Owner: ...
    def events(self, pet_id: str | None = None) -> list[CareEvent]: ...
    def plans(self) -> list[Plan]: ...
    def memberships(self) -> list[Membership]: ...
    def benefit_uses(self, pet_id: str) -> list[BenefitUse]: ...
    def estimates(self, pet_id: str) -> list[Estimate]: ...
    def contact(self) -> ClinicContact: ...
    def payment_options(self) -> list[str]: ...
